"""采集器自动识别的分数阶梯。

⚠️ 为什么单独一个模块: `collectors/__init__.py` 会在末尾导入所有 spider,
而 spider 又需要读这些常量 —— 若常量留在 `__init__` 里, 导入顺序必然成环。
这个模块**不 import 任何东西**, 谁都可以安全引用。

规则很简单: **分数 > `SCORE_GENERIC` 的, 都算"专用采集器认领"**;
专用采集器之间的分差只用于表达"这个 URL 形态有多坐实"。
"""


#: 通用采集器: 什么 http(s) 链接都能"试着抓", 所以永远参与竞争,
#: 但必须低于**所有**专用采集器, 否则专用采集器永远选不上。
SCORE_GENERIC = -1000

#: 输入就是一串图集 ID(没有协议、没有路径)。
#: 分数刻意给得低: 任何图集站都能认领纯 ID, 多个站点并列时由上层判为 ambiguous,
#: 让用户挑 —— 这是诚实的做法, 因为纯 ID 本身确实不带站点信息。
SCORE_BARE_ID = 10

#: 资源直链: 命中站点声明的资源根(https://img.x.com/photos/{gid}/00001.jpg)。
SCORE_RESOURCE_URL = 50

#: 相册页 URL: 命中站点声明的相册页模板所在域名。
#: 比直链高, 因为页面 URL 里往往还带着可以用于命名/计数/视频清单的元信息。
SCORE_ALBUM_PAGE = 100
